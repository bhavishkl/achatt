-- Assign stable sequential receipt numbers to all patient advance entries.
-- Existing rows receive numbers starting at 0001; future rows continue the sequence.
ALTER TABLE public.patient_advances
  ADD COLUMN IF NOT EXISTS receipt_no BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1);

CREATE UNIQUE INDEX IF NOT EXISTS patient_advances_receipt_no_uidx
  ON public.patient_advances (receipt_no);
